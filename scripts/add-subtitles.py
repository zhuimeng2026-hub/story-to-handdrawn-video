def main() -> int:
    ap = argparse.ArgumentParser(description="Inject subtitles into batch storyboards")
    ap.add_argument("--force", action="store_true", help="overwrite existing subtitles")
    args = ap.parse_args()

    if not BOARD_DIR.is_dir():
        sys.exit(f"missing {BOARD_DIR}")

    changed, missing_files, missing_scenes = 0, [], []

    for stem, mapping in TRANSLATIONS.items():
        path = BOARD_DIR / f"{stem}.json"
        if not path.exists():
            missing_files.append(stem)
            continue

        board = json.loads(path.read_text(encoding="utf-8"))
        scenes = board if isinstance(board, list) else board.get("scenes", [])
        if not scenes:
            missing_files.append(f"{stem} (no scenes)")
            continue

        dirty = False
        for scene in scenes:
            want = mapping.get(scene["id"])
            if want is None:
                missing_scenes.append(f"{stem}/{scene['id']}")
                continue
            if scene.get("subtitle") == want:
                continue
            if scene.get("subtitle") and not args.force:
                continue
            scene["subtitle"] = want
            dirty = True

        if dirty:
            # Preserve the original container shape: some batch files are a bare
            # list, others wrap scenes in an object that also holds `project`.
            if isinstance(board, list):
                path.write_text(json.dumps(scenes, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            else:
                path.write_text(json.dumps(board, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            changed += 1
            print(f"  ✓ {stem}")

    print(f"\n更新 {changed} 个 storyboard")
    if missing_files:
        print(f"缺文件: {', '.join(missing_files)}")
    if missing_scenes:
        print(f"缺场景: {', '.join(missing_scenes)}")
    return 1 if (missing_files or missing_scenes) else 0


if __name__ == "__main__":
    raise SystemExit(main())
